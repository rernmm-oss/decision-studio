// Only localize product-owned demo text; freeform decision inputs stay verbatim.
export function reportText(text, lang) {
  if (lang !== 'zh' || typeof text !== 'string') return text;
  if (Object.hasOwn(ZH, text)) return ZH[text];
  let match = text.match(/^You’re weighing (.+)\. Your priorities point toward a thoughtful choice with one clear next step\.$/s);
  if (match) return `你正在权衡 ${match[1].replaceAll(' versus ', ' 与 ')}。你的优先事项能帮助你看清取舍，并找到下一步。`;
  match = text.match(/^(.+) edges ahead when we combine what matters most to you\. This is a decision aid, not a prediction — your lived context still matters\.$/s);
  if (match) return `综合你重视的因素，${match[1]} 暂时略占优势。这只是辅助思考，不是预测；你的实际情况同样重要。`;
  match = text.match(/^You feel glad you chose (.+), with a story or skill that compounds over time\.$/s);
  if (match) return `你庆幸选择了 ${match[1]}，并获得一段值得回味的经历或一项不断积累的技能。`;
  match = text.match(/^Spend 20 minutes gathering one concrete piece of evidence about (.+)\.$/s);
  if (match) return `花 20 分钟，为 ${match[1]} 收集一条具体的信息，帮助你减少不确定性。`;
  return text;
}
